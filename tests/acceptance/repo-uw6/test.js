// Frozen acceptance test — repo-uw6: the freeze gate's brittleness lint
// (DESIGN.md §3.2, "below the panel, move 6"; change-log row `freeze-brittleness-lint`).
// Written before implementation, from the spec alone; criteria C1–C7. Plain Node,
// Docker-free, node built-ins only.
//
// Six deliberate choices, five of them forced by the panel:
//
//   * EVERY SHAPE FIRES ON A SET OF VARIANTS, never one line. One literal instance per
//     shape is passed with full marks by a detector implemented as a LOOKUP TABLE over
//     the four fixture lines — and C1's deleted-lines run cannot catch that, because a
//     text-keyed table fires on the brittle copy and not on the clean one. Variants
//     generated by transformation cannot be table-matched.
//
//   * THE NEAR-MISS PAIRS ARE THE POINT OF THE WHOLE SUITE. For each shape, one line that
//     must fire and one that must not, differing in exactly the feature the rule turns on.
//     Two of the four are verbatim house patterns from this repo's own frozen suites: six
//     suites compare two COMPUTED digests as their "writes nothing" guard, and repo-1cy
//     runs git against refs it created itself. A detector keyed on `createHash` or on
//     `git diff` flags all seven and is wrong — and scores full marks on C2.
//
//   * THE PROSE COMMENT AND THE DECOY SIT NEAR LINE 3, THE SHAPES AT LINE 30+. A lint that
//     greps prose reports line 3; one that reports the file but not the line reports 1;
//     one that matches the decoy reports the wrong line. One fixture is CRLF, which is
//     this working copy's reality and breaks a naive line counter.
//
//   * THE EXIT CODE IS ASSERTED IN BOTH DIRECTIONS AND PAIRED WITH "THE LINT FIRED". The
//     exit-code half alone is passed perfectly by a lint that is wired in and silently
//     returns nothing. The green and indeterminate arms catch an `if (findings.length)
//     return 1`, which is invisible on the red arm because red already exits 0.
//
//   * THE DIGEST IN C7 IS OVER A PURPOSE-BUILT TEMP REPO, paths sorted, content bytes
//     only, mtime excluded. Digesting the live checkout would sweep `.git`, the
//     git-ignored `runs/`, `tools/mapbuild/node_modules` and anything a concurrent sweep
//     is writing — red at random, for reasons unrelated to the lint.
//
//   * NO FIXTURE IS COMMITTED. `tools/run-acceptance.sh` executes every *.js and *.sh in
//     this directory AS A TEST, so a fixture beside this file would be run as one.
//     Everything is built at runtime under os.tmpdir(); the CRLF file is written with
//     explicit \r\n rather than relying on a checked-in file.
'use strict';

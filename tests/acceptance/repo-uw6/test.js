const ROOT = path.resolve(__dirname, '..', '..', '..');
let failed = 0;
function check(name, cond) {
  console.log(`${cond ? 'ok' : 'FAIL'} - ${name}`);
  if (!cond) failed = 1;
}
function safe(label, fn, fallback) {
  try { return fn(); } catch (e) {
    check(`${label} must not throw (threw: ${e && e.message})`, false);
    return fallback;
  }
}
const gate = (() => {
  try { return require(path.join(ROOT, 'scripts', 'freeze-gate.js')); } catch { return null; }
})();
if (!gate) { check('scripts/freeze-gate.js loads', false); process.exit(1); }


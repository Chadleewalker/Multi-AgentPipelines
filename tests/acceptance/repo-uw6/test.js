check('freeze-gate exports brittleFindings(text, file) and lintSuite(dirOrFile)', hasLint);

// --- fixture construction -------------------------------------------------------------

// Each shape file: a prose comment and a decoy near line 3, padding, then the variants at
// known lines from line 30. Returns { text, lines: {variantIndex -> lineNumber}, decoyLine }.
function shapeFile(prose, decoy, variants, eol) {
  const L = ['// fixture', '//', `// ${prose}`, decoy, ''];
  const decoyLine = 4;
  while (L.length < 29) L.push(`const pad${L.length} = ${L.length};`);
  const lines = [];
  for (const v of variants) {
    lines.push(L.length + 1);
    for (const part of v.split('\n')) L.push(part);
  }
  return { text: L.join(eol || '\n'), variantLines: lines, decoyLine };
}


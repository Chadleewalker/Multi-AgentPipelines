// The digest: purpose-built temp repo, sorted paths, content bytes only, never mtime.
function digestOf(root) {
  const out = [];
  (function walk(d, rel) {
    let entries;
    try { entries = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of entries.map((x) => x.name).sort()) {
      const abs = path.join(d, e);
      const r = rel ? `${rel}/${e}` : e;
      let st; try { st = fs.statSync(abs); } catch { continue; }
      if (st.isDirectory()) walk(abs, r);
      else {
        let b; try { b = fs.readFileSync(abs); } catch { b = Buffer.alloc(0); }
        out.push(r + '\0' + crypto.createHash('sha1').update(b).digest('hex'));
      }
    }
  }(root, ''));
  return crypto.createHash('sha1').update(out.join('\n')).digest('hex');
}

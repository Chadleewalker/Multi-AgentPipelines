const capture = () => {
  const o = console.log; const e = console.error;
  let buf = '';
  console.log = (...a) => { buf += a.join(' ') + '\n'; };
  console.error = (...a) => { buf += a.join(' ') + '\n'; };
  return () => { console.log = o; console.error = e; return buf; };
};
const runMain = (args) => {
  const done = capture();
  let code;
  try { code = gate.main(args); } catch (err) { code = `threw: ${err && err.message}`; }
  return { code, out: done() };
};
